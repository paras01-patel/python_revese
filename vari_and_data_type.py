# Variables and Data Types in Python
# Variable Kya Hota Hai?

# Variable ek container hota hai jo data ko store karta hai.

# name = "Paras"
# age = 21

# print(name)
# print(age)

# Output:

# Paras
# 21
# Variable Naming Rules

# ✅ Variable letter ya underscore _ se start hona chahiye.

# name = "Paras"
# _age = 21

# ❌ Number se start nahi ho sakta.

# 1name = "Paras"   # Error

# ❌ Python keywords use nahi kar sakte.

# class = "Python"   # Error
# Data Types

# Data Type batata hai ki variable me kis type ka data store hai.

# 1. Integer (int)

# Puri numbers.

# age = 21

# print(age)
# print(type(age))

# Output:

# 21
# <class 'int'>
# 2. Float (float)

# Decimal numbers.

# price = 99.99

# print(type(price))

# Output:

# <class 'float'>
# 3. String (str)

# Text ya characters.

# name = "Paras"

# print(type(name))

# Output:

# <class 'str'>
# 4. Boolean (bool)

# Sirf True ya False.

# is_student = True

# print(type(is_student))

# Output:

# <class 'bool'>
# 5. List (list)

# Multiple values store karta hai.

# numbers = [10, 20, 30]

# print(type(numbers))

# Output:

# <class 'list'>
# 6. Tuple (tuple)

# Immutable collection.

# data = (10, 20, 30)

# print(type(data))

# Output:

# <class 'tuple'>
# 7. Set (set)

# Unique values store karta hai.

# nums = {1, 2, 3, 4}

# print(type(nums))

# Output:

# <class 'set'>
# 8. Dictionary (dict)

# Key-Value pair me data store karta hai.

# student = {
#     "name": "Paras",
#     "age": 21
# }

# print(type(student))

# Output:

# <class 'dict'>